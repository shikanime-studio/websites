import { existsSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import sidebars from "./sidebars";

const docsRoot = join(import.meta.dirname, "docs");

interface Autogenerated {
  type: "autogenerated";
  dirName: string;
}

describe("sidebars", () => {
  it("autogenerates every sidebar from a real docs folder", () => {
    for (const [name, items] of Object.entries(sidebars)) {
      expect(items, name).toHaveLength(1);
      const [entry] = items as Autogenerated[];

      expect(entry.type).toBe("autogenerated");
      expect(existsSync(join(docsRoot, entry.dirName)), entry.dirName).toBe(
        true,
      );
    }
  });

  it("does not reuse a folder across sidebars", () => {
    const dirs = Object.values(sidebars)
      .flat()
      .map((entry) => (entry as Autogenerated).dirName);

    expect(new Set(dirs).size).toBe(dirs.length);
  });
});
